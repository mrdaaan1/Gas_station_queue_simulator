#!/bin/bash
# Озвучка новостей и рекламы для радио голосами macOS (Milena и Yuri).
# Файлы складываются в Assets/Resources/RadioNews (в Git не попадают — голоса Apple только для себя).
#
# Запуск (на Mac, в Терминале):
#   cd ~/Gas_station_queue_simulator && bash Tools/make_radio_news.sh
#
# Если голосов нет: Системные настройки → Универсальный доступ → Устная речь (Spoken Content) →
# Системный голос → «Управление голосами…» → Русский → поставить галочки Milena и Yuri → скачать.
set -e
cd "$(dirname "$0")/.."
OUT="Assets/Resources/RadioNews"
mkdir -p "$OUT"

# Лучший установленный вариант голоса: Premium → Enhanced → обычный.
# say -v '?' печатает строки вида «Milena (Enhanced)   ru_RU    # Здравствуйте…»
pick_voice() {
  say -v '?' | grep "ru_RU" | sed -E 's/ {2,}.*//' | grep "^$1" | awk '{ p = /Premium/ ? 0 : /Enhanced/ ? 1 : 2; print p "\t" $0 }' | sort | head -1 | cut -f2-
}

FEMALE="$(pick_voice Milena)"; MALE="$(pick_voice Yuri)"
if [ -z "$FEMALE" ]; then
  echo "Нет голоса Milena. Установите его (см. начало скрипта) и запустите снова."
  echo "Русские голоса, которые есть сейчас:"; say -v '?' | grep ru_RU || echo "  (ни одного)"
  exit 1
fi
if [ -z "$MALE" ]; then
  echo "Нет голоса Yuri — все выпуски прочитает $FEMALE."
  MALE="$FEMALE"
fi
echo "Голоса: «$FEMALE» и «$MALE»"

# Голос диктора: m — мужской, f — женский. Скорость чуть быстрее обычной — как у радиоведущих.
n=0
speak() {
  local who="$1" name="$2" text="$3"
  local voice="$FEMALE"; [ "$who" = "m" ] && voice="$MALE"
  n=$((n + 1))
  local file="$OUT/$(printf '%02d' $n)_$name.wav"
  say -v "$voice" -r 185 --file-format=WAVE --data-format=LEI16@22050 -o "$file" "$text"
  echo "  ✓ $file ($voice)"
}

echo "== Озвучиваю новости..."
speak f news_stable "Новости. Ситуация с топливом в регионе стабильная. Дефицита бензина нет. Есть повышенный спрос, который будет удовлетворён в порядке живой очереди."
speak m news_price "Экономика. Цена на девяносто второй выросла на сорок копеек. Эксперты подчёркивают: это не рост цен, а плановая корректировка вверх."
speak f news_queue "Дорожная обстановка. На заправках города наблюдается небольшое скопление автомобилей. Средняя длина небольшого скопления — четыре километра."
speak m news_deliver "Срочно. Бензовоз выехал. Куда — не уточняется. Когда приедет — тоже. Оставайтесь на нашей волне и в своей очереди."
speak f news_minister "Профильное министерство призвало граждан не создавать ажиотаж и заправляться только по необходимости. Например, когда кончился бензин."
speak m news_record "Хорошие новости. Очередь на заправке ЛУКАВОЙЛ установила новый рекорд города. Поздравляем всех участников."
speak f news_tip "Совет водителям. Чтобы сэкономить топливо, глушите двигатель в очереди. А чтобы сэкономить нервы — не смотрите на табло с ценами."
speak m news_weather "Погода. Ночью ожидается похолодание. Водителям в очереди рекомендуем взять плед, термос и запасное терпение."
speak f news_neighbor "По непроверенным данным, на соседней заправке бензин есть. По проверенным — там тоже очередь."
speak m news_survey "Опрос показал: девяносто процентов водителей довольны ситуацией с топливом. Остальные десять процентов стояли в очереди и опрос не прошли."

echo "== Озвучиваю рекламу..."
speak f ad_lukavoil "ЛУКАВОЙЛ. Бензин есть всегда. Кроме сегодня. И вчера. Звёздочка — условия акции уточняйте у заправщика."
speak m ad_vip "Надоели очереди? Талон без очереди — всего за пять тысяч рублей! Звоните прямо сейчас. Номер не скажем, вы его и так знаете."
speak f ad_pies "Пирожки от тёти Вали. С картошкой, с капустой, с ожиданием. Ищите тётю Валю вдоль очереди."
speak m ad_canister "Канистра по блату. Двадцать литров по цене шестидесяти. Без чека, без вопросов, без гарантий."

echo "== Озвучиваю заставки станции..."
speak f jingle_1 "Вы слушаете радио «Очередь эф эм». Мы стоим вместе с вами."
speak m jingle_2 "Радио «Очередь эф эм». Музыка, пока вы ждёте. А ждать вы будете долго."

echo
echo "Готово: $n файлов в $OUT"
echo "Откройте Unity — она сама их подхватит."
open "$OUT" 2>/dev/null || true
